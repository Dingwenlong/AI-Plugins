def qname(name: str) -> str:
    return W + name


def attr(element: ET.Element | None, name: str, default: str = "") -> str:
    if element is None:
        return default
    return element.attrib.get(qname(name), default)


def norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def compact(text: str) -> str:
    return re.sub(r"\s+", "", text or "")


def strip_leading_number(text: str) -> str:
    return re.sub(r"^\s*\d+(?:\.\d+)*[.、]?\s*", "", text).strip()


def text_of(element: ET.Element) -> str:
    return norm("".join(t.text or "" for t in element.findall(".//w:t", NS)))


def truthy_format_prop(rpr: ET.Element | None, tag: str) -> bool:
    if rpr is None:
        return False
    prop = rpr.find(f"w:{tag}", NS)
    if prop is None:
        return False
    value = attr(prop, "val")
    return value.lower() not in {"0", "false", "off", "none"}


def half_point_size(value: str) -> float | None:
    if not value:
        return None
    try:
        return int(value) / 2
    except ValueError:
        return None


def run_size(rpr: ET.Element | None, default_font_size: float | None) -> float | None:
    if rpr is None:
        return default_font_size
    size = rpr.find("w:sz", NS)
    explicit = half_point_size(attr(size, "val")) if size is not None else None
    return explicit if explicit is not None else default_font_size


def cell_format(tc: ET.Element, default_font_size: float | None = None) -> dict[str, Any]:
    tcpr = tc.find("w:tcPr", NS)
    first_p = tc.find("./w:p", NS)
    ppr = first_p.find("w:pPr", NS) if first_p is not None else None
    v_align = attr(tcpr.find("w:vAlign", NS), "val") if tcpr is not None else ""
    jc = attr(ppr.find("w:jc", NS), "val") if ppr is not None else ""

    fonts: set[str] = set()
    runs: list[dict[str, Any]] = []
    bold = False
    italic = False
    for run in tc.findall(".//w:r", NS):
        text = "".join(t.text or "" for t in run.findall(".//w:t", NS))
        rpr = run.find("w:rPr", NS)
        run_fonts: set[str] = set()
        rfonts = rpr.find("w:rFonts", NS) if rpr is not None else None
        if rfonts is not None:
            for value in rfonts.attrib.values():
                if value:
                    fonts.add(value)
                    run_fonts.add(value)
        if text:
            runs.append(
                {
                    "text": text,
                    "eastAsia": font_value(rfonts, "eastAsia"),
                    "ascii": font_value(rfonts, "ascii"),
                    "hAnsi": font_value(rfonts, "hAnsi"),
                    "fonts": sorted(run_fonts),
                    "size": run_size(rpr, default_font_size),
                }
            )
        bold = bold or truthy_format_prop(rpr, "b") or truthy_format_prop(rpr, "bCs")
        italic = italic or truthy_format_prop(rpr, "i") or truthy_format_prop(rpr, "iCs")
    for rpr in tc.findall(".//w:pPr/w:rPr", NS):
        for rfont in rpr.findall("w:rFonts", NS):
            for value in rfont.attrib.values():
                if value:
                    fonts.add(value)
        bold = bold or truthy_format_prop(rpr, "b") or truthy_format_prop(rpr, "bCs")
        italic = italic or truthy_format_prop(rpr, "i") or truthy_format_prop(rpr, "iCs")

    return {
        "text": text_of(tc),
        "vAlign": v_align,
        "jc": jc,
        "fonts": sorted(fonts),
        "runs": runs,
        "bold": bold,
        "italic": italic,
    }


def load_xml(zf: zipfile.ZipFile, name: str) -> ET.Element | None:
    try:
        return ET.fromstring(zf.read(name))
    except KeyError:
        return None


def style_map(zf: zipfile.ZipFile) -> dict[str, str]:
    root = load_xml(zf, "word/styles.xml")
    if root is None:
        return {}
    styles: dict[str, str] = {}
    for style in root.findall(".//w:style", NS):
        style_id = attr(style, "styleId")
        name = style.find("w:name", NS)
        if style_id and name is not None:
            styles[style_id] = attr(name, "val")
    return styles


def default_font_size(zf: zipfile.ZipFile) -> float | None:
    root = load_xml(zf, "word/styles.xml")
    if root is None:
        return None
    size = root.find(".//w:docDefaults/w:rPrDefault/w:rPr/w:sz", NS)
    return half_point_size(attr(size, "val")) if size is not None else None


def parse_blocks(
    zf: zipfile.ZipFile, styles: dict[str, str], inherited_font_size: float | None = None
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    root = load_xml(zf, "word/document.xml")
    if root is None:
        raise ValueError("word/document.xml not found")
    body = root.find("w:body", NS)
    if body is None:
        raise ValueError("word/document.xml has no body")

    blocks: list[dict[str, Any]] = []
    for child in list(body):
        tag = child.tag.split("}")[-1]
        if tag == "p":
            pstyle = child.find("w:pPr/w:pStyle", NS)
            style_id = attr(pstyle, "val") if pstyle is not None else ""
            image_ids = [
                blip.attrib.get(R + "embed", "")
                for blip in child.findall(".//a:blip", NS)
                if blip.attrib.get(R + "embed")
            ]
            image_ids.extend(
                img.attrib.get(R + "id", "")
                for img in child.findall(".//v:imagedata", NS)
                if img.attrib.get(R + "id")
            )
            blocks.append(
                {
                    "type": "p",
                    "text": text_of(child),
                    "style_id": style_id,
                    "style_name": styles.get(style_id, style_id),
                    "image_count": len(image_ids),
                }
            )
        elif tag == "tbl":
            rows: list[list[str]] = []
            cell_formats: list[list[dict[str, Any]]] = []
            for tr in child.findall("./w:tr", NS):
                row: list[str] = []
                fmt_row: list[dict[str, Any]] = []
                for tc in tr.findall("./w:tc", NS):
                    fmt = cell_format(tc, inherited_font_size)
                    row.append(fmt["text"])
                    fmt_row.append(fmt)
                rows.append(row)
                cell_formats.append(fmt_row)
            blocks.append({"type": "tbl", "rows": rows, "cell_formats": cell_formats})
    sections = [section_info(sect) for sect in root.findall(".//w:sectPr", NS)]
    return blocks, sections


def section_info(sect: ET.Element) -> dict[str, str]:
    pg = sect.find("w:pgSz", NS)
    mar = sect.find("w:pgMar", NS)
    info: dict[str, str] = {}
    if pg is not None:
        info.update({"w": attr(pg, "w"), "h": attr(pg, "h"), "orient": attr(pg, "orient")})
    if mar is not None:
        info.update(
            {
                "top": attr(mar, "top"),
                "bottom": attr(mar, "bottom"),
                "left": attr(mar, "left"),
                "right": attr(mar, "right"),
            }
        )
    return info


def footer_text(zf: zipfile.ZipFile) -> str:
    texts: list[str] = []
    for name in zf.namelist():
        if name.startswith("word/footer") and name.endswith(".xml"):
            root = load_xml(zf, name)
            if root is not None:
                value = text_of(root)
                if value:
                    texts.append(value)
    return " | ".join(texts)


def font_value(rfonts: ET.Element | None, name: str) -> str:
    if rfonts is None:
        return ""
    return rfonts.attrib.get(qname(name), "")


def word_part_label(name: str) -> str:
    if name == "word/document.xml":
        return "document"
    if name.startswith("word/header"):
        return name.removeprefix("word/").removesuffix(".xml")
    if name.startswith("word/footer"):
        return name.removeprefix("word/").removesuffix(".xml")
    return name


def check_docx_font_policy(checks: list[Check], zf: zipfile.ZipFile) -> None:
    bad_chinese: list[str] = []
    bad_latin: list[str] = []
    checked_runs = 0
    part_names = [
        name
        for name in zf.namelist()
        if name == "word/document.xml"
        or (name.startswith("word/header") and name.endswith(".xml"))
        or (name.startswith("word/footer") and name.endswith(".xml"))
    ]

    for name in part_names:
        root = load_xml(zf, name)
        if root is None:
            continue
        label = word_part_label(name)
        run_no = 0
        for run in root.findall(".//w:r", NS):
            text = "".join(t.text or "" for t in run.findall(".//w:t", NS))
            if not text.strip():
                continue
            run_no += 1
            rfonts = run.find("w:rPr/w:rFonts", NS)
            east_asia = font_value(rfonts, "eastAsia")
            ascii_font = font_value(rfonts, "ascii")
            hansi_font = font_value(rfonts, "hAnsi")
            checked_runs += 1

            if CJK_RE.search(text) and east_asia and east_asia not in EXPECTED_CHINESE_FONTS:
                bad_chinese.append(f"{label} run {run_no}: eastAsia `{east_asia}` in `{text[:30]}`")
            if LATIN_NUMBER_RE.search(text):
                for kind, value in (("ascii", ascii_font), ("hAnsi", hansi_font)):
                    if value and value != EXPECTED_LATIN_FONT:
                        bad_latin.append(f"{label} run {run_no}: {kind} `{value}` in `{text[:30]}`")
                        break

    if bad_chinese:
        add(
            checks,
            "WARN",
            "font.policy_chinese",
            "Chinese text should use `微軟正黑體`.",
            "; ".join(bad_chinese[:12]) + ("; ..." if len(bad_chinese) > 12 else ""),
        )
    if bad_latin:
        add(
            checks,
            "WARN",
            "font.policy_latin",
            "Non-Chinese Latin/numeric text should use `Times New Roman`.",
            "; ".join(bad_latin[:12]) + ("; ..." if len(bad_latin) > 12 else ""),
        )
    if not bad_chinese and not bad_latin:
        add(
            checks,
            "PASS",
            "font.policy",
            "No explicit font drift was found for Chinese or Latin/numeric text.",
            f"{checked_runs} visible text run(s) checked",
        )


def add(checks: list[Check], status: str, rule: str, message: str, evidence: str = "") -> None:
    checks.append(Check(status=status, rule=rule, message=message, evidence=evidence))


def has_heading_style(block: dict[str, Any]) -> bool:
    style = (block.get("style_name") or block.get("style_id") or "").lower().replace(" ", "")
    return style in {"heading1", "1"} or style.startswith("heading1")


def find_heading_indices(blocks: list[dict[str, Any]]) -> dict[str, int]:
    found: dict[str, int] = {}
    expected_compact = {compact(h): h for h in EXPECTED_HEADINGS}
    for index, block in enumerate(blocks):
        if block.get("type") != "p":
            continue
        body_text = compact(strip_leading_number(block.get("text", "")))
        if body_text in expected_compact and expected_compact[body_text] not in found:
            found[expected_compact[body_text]] = index
    return found


def blocks_between(blocks: list[dict[str, Any]], start: int, end: int | None) -> list[dict[str, Any]]:
    return blocks[start + 1 : end if end is not None else len(blocks)]


def find_table_by_header(blocks: list[dict[str, Any]], header: list[str]) -> dict[str, Any] | None:
    wanted = [compact(x) for x in header]
    for block in blocks:
        if block.get("type") != "tbl" or not block.get("rows"):
            continue
        first = [compact(x) for x in block["rows"][0][: len(header)]]
        if first == wanted:
            return block
    return None


def non_empty_text(blocks: list[dict[str, Any]]) -> list[str]:
    values: list[str] = []
    for block in blocks:
        if block.get("type") == "p" and block.get("text"):
            values.append(block["text"])
        elif block.get("type") == "tbl":
            for row in block.get("rows", []):
                values.extend(cell for cell in row if cell)
    return values


def text_locations(blocks: list[dict[str, Any]]) -> list[tuple[str, str]]:
    locations: list[tuple[str, str]] = []
    paragraph_no = 0
    table_no = 0
    for block in blocks:
        if block.get("type") == "p":
            text = block.get("text", "")
            if text:
                paragraph_no += 1
                locations.append((f"paragraph {paragraph_no}", text))
        elif block.get("type") == "tbl":
            table_no += 1
            for row_no, row in enumerate(block.get("rows", []), start=1):
                for col_no, cell in enumerate(row, start=1):
                    if cell:
                        locations.append((f"table {table_no} row {row_no} col {col_no}", cell))
    return locations


def check_language_traditional_chinese(checks: list[Check], blocks: list[dict[str, Any]]) -> None:
    findings: list[str] = []
    seen: set[tuple[str, str]] = set()
    for location, text in text_locations(blocks):
        for index, char in enumerate(text):
            if char in AMBIGUOUS_TRADITIONAL_CHARS:
                continue
            traditional = SIMPLIFIED_TO_TRADITIONAL.get(char)
            if not traditional:
                continue
            key = (location, char)
            if key in seen:
                continue
            seen.add(key)
            start = max(0, index - 12)
            end = min(len(text), index + 13)
            excerpt = text[start:end]
            findings.append(f"{location}: `{char}` -> `{traditional}` in `{excerpt}`")

    if findings:
        add(
            checks,
            "FAIL",
            "language.traditional_chinese",
            "Chinese content must use Traditional Chinese; Simplified Chinese characters were found.",
            "; ".join(findings[:12]) + ("; ..." if len(findings) > 12 else ""),
        )
    else:
        add(checks, "PASS", "language.traditional_chinese", "No Simplified Chinese characters were found in visible text.")


def check_preferred_terminology(checks: list[Check], blocks: list[dict[str, Any]]) -> None:
    findings: list[str] = []
    seen: set[tuple[str, str]] = set()
    for location, text in text_locations(blocks):
        for term, replacement in PREFERRED_TERMS.items():
            start_at = 0
            while True:
                index = text.find(term, start_at)
                if index < 0:
                    break
                key = (location, term)
                if key not in seen:
                    seen.add(key)
                    start = max(0, index - 12)
                    end = min(len(text), index + len(term) + 12)
                    excerpt = text[start:end]
                    findings.append(f"{location}: `{term}` -> `{replacement}` in `{excerpt}`")
                start_at = index + len(term)

    if findings:
        add(
            checks,
            "WARN",
            "language.preferred_terminology",
            "Use project preferred wording: replace `校驗` with `驗證` for validation meaning or `檢核` for checklist/checking meaning.",
            "; ".join(findings[:12]) + ("; ..." if len(findings) > 12 else ""),
        )
    else:
        add(checks, "PASS", "language.preferred_terminology", "No disallowed `校驗` wording was found in visible text.")


def format_cell_ref(row_no: int, col_no: int, header: list[str] | None = None) -> str:
    col_name = header[col_no - 1] if header and col_no - 1 < len(header) else f"col {col_no}"
    return f"row {row_no} `{col_name}`"


def has_font(cell: dict[str, Any], font_name: str) -> bool:
    return any(font_name.lower() in font.lower() for font in cell.get("fonts", []))


def check_revision_table_format(checks: list[Check], table: dict[str, Any]) -> None:
    formats = table.get("cell_formats", [])
    missing_vertical: list[str] = []
    dengxian_cells: list[str] = []
    centered_notes: list[str] = []
    bad_sizes: list[str] = []
    for row_index, row in enumerate(formats[1:], start=2):
        for col_index, cell in enumerate(row[: len(REVISION_HEADER)], start=1):
            if cell.get("vAlign") != "center":
                missing_vertical.append(format_cell_ref(row_index, col_index, REVISION_HEADER))
            if has_font(cell, "DengXian"):
                dengxian_cells.append(format_cell_ref(row_index, col_index, REVISION_HEADER))
            for run_index, run in enumerate(cell.get("runs", []), start=1):
                text = run.get("text", "")
                if text.strip() and run.get("size") != EXPECTED_REVISION_TABLE_FONT_SIZE:
                    bad_sizes.append(
                        f"{format_cell_ref(row_index, col_index, REVISION_HEADER)} run {run_index}: "
                        f"{run.get('size') or '<missing>'}pt in `{text[:30]}`"
                    )
        if len(row) >= 5 and row[4].get("jc") == "center" and len(compact(row[4].get("text", ""))) > 8:
            centered_notes.append(format_cell_ref(row_index, 5, REVISION_HEADER))

    if missing_vertical:
        add(
            checks,
            "WARN",
            "revision.table_vertical_alignment",
            "Revision table data cells should keep vertical center alignment.",
            "; ".join(missing_vertical[:12]) + ("; ..." if len(missing_vertical) > 12 else ""),
        )
    if dengxian_cells:
        add(
            checks,
            "WARN",
            "revision.table_font",
            "Revision table data cells should keep the sample Chinese fonts, not DengXian.",
            "; ".join(dengxian_cells[:12]) + ("; ..." if len(dengxian_cells) > 12 else ""),
        )
    if centered_notes:
        add(
            checks,
            "WARN",
            "revision.note_alignment",
            "Revision note cells should not be center-aligned because it changes wrapping.",
            "; ".join(centered_notes[:12]) + ("; ..." if len(centered_notes) > 12 else ""),
        )
    if bad_sizes:
        add(
            checks,
            "WARN",
            "revision.table_font_size",
            "Revision table data cells should use 12 pt font size.",
            "; ".join(bad_sizes[:12]) + ("; ..." if len(bad_sizes) > 12 else ""),
        )


def check_sequence_table_format(checks: list[Check], table: dict[str, Any]) -> None:
    formats = table.get("cell_formats", [])
    missing_vertical: list[str] = []
    bad_alignment: list[str] = []
    for row_index, row in enumerate(formats[1:], start=2):
        for col_index, cell in enumerate(row[: len(SEQUENCE_HEADER)], start=1):
            if cell.get("vAlign") != "center":
                missing_vertical.append(format_cell_ref(row_index, col_index, SEQUENCE_HEADER))
        for col_index in (1, 2):
            if len(row) >= col_index and row[col_index - 1].get("jc") != "center":
                bad_alignment.append(format_cell_ref(row_index, col_index, SEQUENCE_HEADER))
        if len(row) >= 3 and row[2].get("jc") == "both":
            bad_alignment.append(format_cell_ref(row_index, 3, SEQUENCE_HEADER))

    if missing_vertical:
        add(
            checks,
            "WARN",
            "sequence.table_vertical_alignment",
            "Sequence table data cells should keep vertical center alignment.",
            "; ".join(missing_vertical[:12]) + ("; ..." if len(missing_vertical) > 12 else ""),
        )
    if bad_alignment:
        add(
            checks,
            "WARN",
            "sequence.table_alignment",
            "Sequence table data cell alignment differs from the sample.",
            "; ".join(bad_alignment[:12]) + ("; ..." if len(bad_alignment) > 12 else ""),
        )


def is_left_like_alignment(value: str) -> bool:
    return value in {"", "left", "both", "start"}


def api_table_font_drift(cell: dict[str, Any], row_index: int, col_index: int) -> tuple[list[str], list[str]]:
    bad_chinese: list[str] = []
    bad_latin: list[str] = []
    ref = format_cell_ref(row_index, col_index, API_HEADER)
    for run_index, run in enumerate(cell.get("runs", []), start=1):
        text = run.get("text", "")
        if not text.strip():
            continue
        if CJK_RE.search(text):
            east_asia = run.get("eastAsia", "")
            if east_asia and east_asia not in EXPECTED_CHINESE_FONTS:
                bad_chinese.append(f"{ref} run {run_index}: eastAsia `{east_asia}` in `{text[:30]}`")
        if LATIN_NUMBER_RE.search(text):
            for kind in ("ascii", "hAnsi"):
                value = run.get(kind, "")
                if value and value != EXPECTED_LATIN_FONT:
                    bad_latin.append(f"{ref} run {run_index}: {kind} `{value}` in `{text[:30]}`")
                    break
    return bad_chinese, bad_latin


def api_table_simplified_findings(cell: dict[str, Any], row_index: int, col_index: int) -> list[str]:
    findings: list[str] = []
    text = cell.get("text", "")
    ref = format_cell_ref(row_index, col_index, API_HEADER)
    seen: set[str] = set()
    for index, char in enumerate(text):
        if char in AMBIGUOUS_TRADITIONAL_CHARS or char in seen:
            continue
        traditional = SIMPLIFIED_TO_TRADITIONAL.get(char)
        if not traditional:
            continue
        seen.add(char)
        start = max(0, index - 12)
        end = min(len(text), index + 13)
        findings.append(f"{ref}: `{char}` -> `{traditional}` in `{text[start:end]}`")
    return findings


def check_api_table_format(checks: list[Check], table: dict[str, Any]) -> None:
    formats = table.get("cell_formats", [])
    header_alignment: list[str] = []
    data_vertical: list[str] = []
    data_horizontal: list[str] = []
    italic_cells: list[str] = []
    unexpected_bold: list[str] = []
    bad_chinese_fonts: list[str] = []
    bad_latin_fonts: list[str] = []
    bad_sizes: list[str] = []
    simplified_cells: list[str] = []

    for col_index, cell in enumerate(formats[0][: len(API_HEADER)] if formats else [], start=1):
        if cell.get("vAlign") != "center" or cell.get("jc") != "center":
            header_alignment.append(
                f"{format_cell_ref(1, col_index, API_HEADER)}: vAlign={cell.get('vAlign') or '<default>'}, jc={cell.get('jc') or '<default>'}"
            )
        cell_bad_chinese, cell_bad_latin = api_table_font_drift(cell, 1, col_index)
        bad_chinese_fonts.extend(cell_bad_chinese)
        bad_latin_fonts.extend(cell_bad_latin)
        for run_index, run in enumerate(cell.get("runs", []), start=1):
            text = run.get("text", "")
            if text.strip() and run.get("size") != EXPECTED_API_TABLE_FONT_SIZE:
                bad_sizes.append(
                    f"{format_cell_ref(1, col_index, API_HEADER)} run {run_index}: "
                    f"{run.get('size') or '<missing>'}pt in `{text[:30]}`"
                )
        simplified_cells.extend(api_table_simplified_findings(cell, 1, col_index))

    for row_index, row in enumerate(formats[1:], start=2):
        for col_index, cell in enumerate(row[: len(API_HEADER)], start=1):
            if cell.get("vAlign") != "center":
                data_vertical.append(format_cell_ref(row_index, col_index, API_HEADER))
            if not is_left_like_alignment(cell.get("jc", "")):
                data_horizontal.append(
                    f"{format_cell_ref(row_index, col_index, API_HEADER)}: jc={cell.get('jc') or '<default>'}"
                )
            if cell.get("italic"):
                italic_cells.append(format_cell_ref(row_index, col_index, API_HEADER))
            cell_bad_chinese, cell_bad_latin = api_table_font_drift(cell, row_index, col_index)
            bad_chinese_fonts.extend(cell_bad_chinese)
            bad_latin_fonts.extend(cell_bad_latin)
            for run_index, run in enumerate(cell.get("runs", []), start=1):
                text = run.get("text", "")
                if text.strip() and run.get("size") != EXPECTED_API_TABLE_FONT_SIZE:
                    bad_sizes.append(
                        f"{format_cell_ref(row_index, col_index, API_HEADER)} run {run_index}: "
                        f"{run.get('size') or '<missing>'}pt in `{text[:30]}`"
                    )
            simplified_cells.extend(api_table_simplified_findings(cell, row_index, col_index))
        for col_index in (1, 2):
            if len(row) >= col_index and row[col_index - 1].get("bold"):
                unexpected_bold.append(format_cell_ref(row_index, col_index, API_HEADER))

    if header_alignment:
        add(
            checks,
            "WARN",
            "api.table_header_alignment",
            "API list header cells should keep horizontal and vertical center alignment.",
            "; ".join(header_alignment[:12]) + ("; ..." if len(header_alignment) > 12 else ""),
        )
    if data_vertical:
        add(
            checks,
            "WARN",
            "api.table_vertical_alignment",
            "API list data cells should keep vertical center alignment.",
            "; ".join(data_vertical[:12]) + ("; ..." if len(data_vertical) > 12 else ""),
        )
    if data_horizontal:
        add(
            checks,
            "WARN",
            "api.table_data_alignment",
            "API list data cells should keep left/justified horizontal alignment.",
            "; ".join(data_horizontal[:12]) + ("; ..." if len(data_horizontal) > 12 else ""),
        )
    if italic_cells:
        add(
            checks,
            "WARN",
            "api.table_italic",
            "API list data cells should not use italic formatting.",
            "; ".join(italic_cells[:12]) + ("; ..." if len(italic_cells) > 12 else ""),
        )
    if unexpected_bold:
        add(
            checks,
            "WARN",
            "api.table_bold",
            "API類別 and API 名稱 data cells should not be bold.",
            "; ".join(unexpected_bold[:12]) + ("; ..." if len(unexpected_bold) > 12 else ""),
        )
    if bad_chinese_fonts:
        add(
            checks,
            "WARN",
            "api.table_font_chinese",
            "API list Chinese text should use `微軟正黑體`.",
            "; ".join(bad_chinese_fonts[:12]) + ("; ..." if len(bad_chinese_fonts) > 12 else ""),
        )
    if bad_latin_fonts:
        add(
            checks,
            "WARN",
            "api.table_font_latin",
            "API list Latin/numeric text should use `Times New Roman`.",
            "; ".join(bad_latin_fonts[:12]) + ("; ..." if len(bad_latin_fonts) > 12 else ""),
        )
    if bad_sizes:
        add(
            checks,
            "WARN",
            "api.table_font_size",
            "API list table cells should use 10 pt font size.",
            "; ".join(bad_sizes[:12]) + ("; ..." if len(bad_sizes) > 12 else ""),
        )
    if simplified_cells:
        add(
            checks,
            "FAIL",
            "api.table_traditional_chinese",
            "API list Chinese content must use Traditional Chinese.",
            "; ".join(simplified_cells[:12]) + ("; ..." if len(simplified_cells) > 12 else ""),
        )

    if not header_alignment and not data_vertical and not data_horizontal:
        add(checks, "PASS", "api.table_alignment", "API list table alignment matches the expected header/data-cell policy.")
    if not bad_chinese_fonts and not bad_latin_fonts and not bad_sizes:
        add(checks, "PASS", "api.table_font", "No explicit API list font drift was found.")
    if not simplified_cells:
        add(checks, "PASS", "api.table_traditional_chinese", "No Simplified Chinese characters were found in the API list table.")


def check_docx(path: Path) -> dict[str, Any]:
    checks: list[Check] = []
    metadata: dict[str, Any] = {"path": str(path)}

    if not path.exists():
        add(checks, "FAIL", "file.exists", "File does not exist.", str(path))
        return summarize(metadata, checks)
    if path.suffix.lower() != ".docx":
        add(checks, "FAIL", "file.extension", "Input file is not a .docx file.", path.name)
        return summarize(metadata, checks)

    filename_match = re.match(r"^TSD\.[A-Za-z]\.\d{3}_.+_v(\d+\.\d+)_(\d{8})\.docx$", path.name)
    if filename_match:
        add(checks, "PASS", "file.name", "Filename matches the sample TSD naming pattern.", path.name)
        metadata["filename_version"] = filename_match.group(1)
        metadata["filename_date"] = filename_match.group(2)
    else:
        add(checks, "WARN", "file.name", "Filename does not match the sample TSD naming pattern.", path.name)

    try:
        with zipfile.ZipFile(path) as zf:
            styles = style_map(zf)
            inherited_font_size = default_font_size(zf)
            blocks, sections = parse_blocks(zf, styles, inherited_font_size)
            footer = footer_text(zf)
            media_count = len([name for name in zf.namelist() if name.startswith("word/media/")])
            check_docx_font_policy(checks, zf)
    except (zipfile.BadZipFile, ValueError, ET.ParseError) as exc:
        add(checks, "FAIL", "docx.readable", "File cannot be read as a valid docx package.", str(exc))
        return summarize(metadata, checks)

    add(checks, "PASS", "docx.readable", "File is a readable docx package.")
    paragraphs = [b for b in blocks if b.get("type") == "p" and b.get("text")]
    all_text = "\n".join(b["text"] for b in paragraphs)
    metadata["paragraphs"] = len(paragraphs)
    metadata["tables"] = len([b for b in blocks if b.get("type") == "tbl"])
    metadata["media_count"] = media_count
    check_language_traditional_chinese(checks, blocks)
    check_preferred_terminology(checks, blocks)

    first_text = "\n".join(b["text"] for b in paragraphs[:12])
    for label in EXPECTED_COVER_LABELS:
        if label in first_text:
            add(checks, "PASS", f"cover.{label}", f"Cover contains `{label}`.")
        else:
            add(checks, "FAIL", f"cover.{label}", f"Cover is missing `{label}`.")

    cover_version = None
    for block in paragraphs[:20]:
        match = re.search(r"版本\s*(\d+\.\d+)", block["text"])
        if match:
            cover_version = match.group(1)
            break
    metadata["cover_version"] = cover_version
    if cover_version:
        add(checks, "PASS", "cover.version", "Cover contains a version line.", f"版本 {cover_version}")
    else:
        add(checks, "FAIL", "cover.version", "Cover is missing a `版本 x.y` line.")

    if "filename_version" in metadata and cover_version and metadata["filename_version"] != cover_version:
        add(
            checks,
            "WARN",
            "file.cover_version",
            "Filename version differs from the cover version.",
            f"filename v{metadata['filename_version']} vs cover v{cover_version}",
        )

    revision_heading_index = next((i for i, b in enumerate(blocks) if b.get("text") == "版本修訂"), None)
    if revision_heading_index is None:
        add(checks, "FAIL", "revision.heading", "Missing `版本修訂` heading.")
    else:
        add(checks, "PASS", "revision.heading", "Found `版本修訂` heading.")

    revision_table = find_table_by_header(blocks, REVISION_HEADER)
    if revision_table is None:
        add(checks, "FAIL", "revision.table", "Missing revision table with the expected header.", " / ".join(REVISION_HEADER))
    else:
        rows = revision_table["rows"]
        add(checks, "PASS", "revision.table", "Found revision table with expected columns.", f"{len(rows) - 1} data rows")
        if len(rows) < 2:
            add(checks, "FAIL", "revision.rows", "Revision table has no data rows.")
        else:
            latest_version = rows[-1][0].strip() if rows[-1] else ""
            metadata["latest_revision_version"] = latest_version
            if cover_version and latest_version != cover_version:
                add(
                    checks,
                    "FAIL",
                    "revision.latest_version",
                    "Latest revision version does not match cover version.",
                    f"latest {latest_version}; cover {cover_version}",
                )
            else:
                add(checks, "PASS", "revision.latest_version", "Latest revision version matches cover version.", latest_version)
            for row_no, row in enumerate(rows[1:], start=2):
                padded = (row + [""] * 5)[:5]
                version, date, author, prd, note = [cell.strip() for cell in padded]
                if not re.match(r"^\d+\.\d+$", version):
                    add(checks, "WARN", "revision.version_format", "Revision version should match major.minor.", f"row {row_no}: {version}")
                if not re.match(r"^\d{4}/\d{2}/\d{2}$", date):
                    add(checks, "WARN", "revision.date_format", "Revision date should match yyyy/mm/dd.", f"row {row_no}: {date}")
                if not author or not prd or not note:
                    add(checks, "WARN", "revision.required_cells", "Revision row has empty required cells.", f"row {row_no}")
            check_revision_table_format(checks, revision_table)

    if "目錄" in all_text:
        add(checks, "PASS", "toc.heading", "Found `目錄` heading.")
    else:
        add(checks, "FAIL", "toc.heading", "Missing `目錄` heading.")
    for index, heading in enumerate(EXPECTED_HEADINGS, start=1):
        pattern = f"{index}. {heading}"
        if any(compact(pattern) in compact(p["text"]) for p in paragraphs):
            add(checks, "PASS", f"toc.entry.{index}", "TOC contains required chapter entry.", pattern)
        else:
            add(checks, "FAIL", f"toc.entry.{index}", "TOC is missing required chapter entry.", pattern)

    heading_indices = find_heading_indices(blocks)
    found_positions = [heading_indices.get(h) for h in EXPECTED_HEADINGS]
    missing = [h for h in EXPECTED_HEADINGS if h not in heading_indices]
    if missing:
        add(checks, "FAIL", "body.headings", "Missing required body headings.", "; ".join(missing))
    elif found_positions == sorted(found_positions):
        add(checks, "PASS", "body.heading_order", "Required body headings appear in sample order.")
    else:
        add(checks, "FAIL", "body.heading_order", "Required body headings are out of order.")

    for heading in EXPECTED_HEADINGS:
        if heading in heading_indices:
            block = blocks[heading_indices[heading]]
            if has_heading_style(block):
                add(checks, "PASS", "body.heading_style", "Body heading uses Heading 1 style.", heading)
            else:
                add(
                    checks,
                    "WARN",
                    "body.heading_style",
                    "Body heading does not appear to use Heading 1 style.",
                    f"{heading}: {block.get('style_name') or block.get('style_id')}",
                )

    ranges: dict[str, list[dict[str, Any]]] = {}
    ordered = [(h, heading_indices[h]) for h in EXPECTED_HEADINGS if h in heading_indices]
    for idx, (heading, start) in enumerate(ordered):
        end = ordered[idx + 1][1] if idx + 1 < len(ordered) else None
        ranges[heading] = blocks_between(blocks, start, end)

    purpose_text = non_empty_text(ranges.get(EXPECTED_HEADINGS[0], []))
    if purpose_text:
        add(checks, "PASS", "section.purpose", "Functional purpose section has content.", purpose_text[0][:120])
    elif EXPECTED_HEADINGS[0] in heading_indices:
        add(checks, "FAIL", "section.purpose", "Functional purpose section is empty.")

    structure_images = sum(b.get("image_count", 0) for b in ranges.get(EXPECTED_HEADINGS[1], []))
    if structure_images:
        add(checks, "PASS", "section.structure_diagram", "Function structure section contains an embedded image.", str(structure_images))
    elif EXPECTED_HEADINGS[1] in heading_indices:
        add(checks, "FAIL", "section.structure_diagram", "Function structure section has no embedded image.")

    sequence_table = find_table_by_header(ranges.get(EXPECTED_HEADINGS[2], []), SEQUENCE_HEADER)
    if sequence_table is not None:
        add(checks, "PASS", "section.sequence_table", "Sequence diagram section has the expected table.", f"{len(sequence_table['rows']) - 1} data rows")
        check_sequence_table_format(checks, sequence_table)
    elif EXPECTED_HEADINGS[2] in heading_indices:
        add(checks, "FAIL", "section.sequence_table", "Sequence diagram section is missing the expected table.", " / ".join(SEQUENCE_HEADER))

    reference_text = non_empty_text(ranges.get(EXPECTED_HEADINGS[3], []))
    if reference_text:
        add(checks, "PASS", "section.reference", "Reference section has content.", reference_text[0][:120])
    elif EXPECTED_HEADINGS[3] in heading_indices:
        add(checks, "FAIL", "section.reference", "Reference section is empty.")

    api_table = find_table_by_header(ranges.get(EXPECTED_HEADINGS[4], []), API_HEADER)
    if api_table is None:
        add(checks, "FAIL", "section.api_table", "API list section is missing the expected table.", " / ".join(API_HEADER))
    else:
        data_rows = api_table["rows"][1:]
        if data_rows:
            add(checks, "PASS", "section.api_table", "API list section has the expected table.", f"{len(data_rows)} data rows")
            for row_no, row in enumerate(data_rows, start=2):
                padded = (row + [""] * 3)[:3]
                if not all(cell.strip() for cell in padded):
                    add(checks, "WARN", "section.api_required_cells", "API list row has empty cells.", f"row {row_no}")
            check_api_table_format(checks, api_table)
        else:
            add(checks, "FAIL", "section.api_table_rows", "API list table has no data rows.")

    if FOOTER_COPYRIGHT in footer:
        add(checks, "PASS", "footer.copyright", "Footer contains the expected copyright text.")
    else:
        add(checks, "FAIL", "footer.copyright", "Footer is missing the expected copyright text.", footer[:160])

    if sections:
        bad_sections: list[str] = []
        for idx, section in enumerate(sections, start=1):
            expected = {"w": "11906", "h": "16838", "top": "1440", "bottom": "1440", "left": "1083", "right": "1083"}
            mismatches = [f"{key}={section.get(key, '')}" for key, value in expected.items() if section.get(key) != value]
            if section.get("orient") not in {"", "portrait"}:
                mismatches.append(f"orient={section.get('orient')}")
            if mismatches:
                bad_sections.append(f"section {idx}: {', '.join(mismatches)}")
        if bad_sections:
            add(checks, "WARN", "page.setup", "Page setup differs from the sample A4 portrait margins.", "; ".join(bad_sections))
        else:
            add(checks, "PASS", "page.setup", "Page setup matches sample A4 portrait margins.", f"{len(sections)} section(s)")
    else:
        add(checks, "WARN", "page.setup", "No section page setup information found.")

    return summarize(metadata, checks)


def summarize(metadata: dict[str, Any], checks: list[Check]) -> dict[str, Any]:
    counts = {"FAIL": 0, "WARN": 0, "PASS": 0}
    for check in checks:
        counts[check.status] = counts.get(check.status, 0) + 1
    return {"metadata": metadata, "counts": counts, "checks": [asdict(c) for c in checks]}


def render_markdown(result: dict[str, Any]) -> str:
    metadata = result["metadata"]
    counts = result["counts"]
    lines = [
        f"# TSD DOCX Compliance Report",
        "",
        f"- File: `{metadata.get('path', '')}`",
        f"- Counts: FAIL={counts.get('FAIL', 0)}, WARN={counts.get('WARN', 0)}, PASS={counts.get('PASS', 0)}",
    ]
    for key in ["cover_version", "latest_revision_version", "filename_version", "media_count", "tables"]:
        if key in metadata:
            lines.append(f"- {key}: `{metadata[key]}`")
    for status in ["FAIL", "WARN", "PASS"]:
        selected = [c for c in result["checks"] if c["status"] == status]
        if not selected:
            continue
        lines.extend(["", f"## {status}"])
        for check in selected:
            evidence = f" ({check['evidence']})" if check.get("evidence") else ""
            lines.append(f"- `{check['rule']}`: {check['message']}{evidence}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("docx", type=Path, help="Path to a TSD .docx file.")
    parser.add_argument("--rules-root", help="专案规则库根目录；未传入时读取 workspace 配置。")
    parser.add_argument("--format", choices=["markdown", "json"], default="markdown", help="Output format.")
    parser.add_argument("--strict-exit", action="store_true", help="Return exit code 1 when FAIL checks exist.")
    args = parser.parse_args(argv)

    rules_root = resolve_rules_root(args.rules_root, start_path=Path(__file__).resolve())
    catalog = load_catalog(rules_root)
    defaults = catalog.get("defaults") if isinstance(catalog.get("defaults"), dict) else {}
    labels = defaults.get("tsdCoverLabels") if isinstance(defaults.get("tsdCoverLabels"), list) else []
    if labels:
        global EXPECTED_COVER_LABELS
        EXPECTED_COVER_LABELS = [str(label).strip() for label in labels if str(label).strip()]

    result = check_docx(args.docx)
    if args.format == "json":
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(render_markdown(result), end="")
    if args.strict_exit and result["counts"].get("FAIL", 0):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
